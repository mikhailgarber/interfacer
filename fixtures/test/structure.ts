/**
 * Extracting a page's structure, with everything a rebrand may change removed.
 *
 * The claim under test is the design's multi-tenant one: branding — colours,
 * class names, chrome, logo — and wording are absorbed by semantic targeting,
 * while a *structural* difference is the tenant difference that earns its own
 * artifact. This reduces a rendered page to the part of it a flow's targets
 * actually depend on, so "same structure" and "different structure" become
 * things a test can assert rather than things a reader has to eyeball.
 *
 * Kept: element nesting and order, tag names, roles, form wiring (`name`,
 * `type`, `for`, `id`, `action`, `method`), and whether a link or frame has a
 * destination at all.
 *
 * Dropped: all text, `class`, `style`, `value`, `data-testid`, `aria-label`,
 * `title`, and the whole of `<head>`. Those are exactly what a rebrand is
 * allowed to change.
 *
 * A tag scanner rather than a real HTML parser. That is safe here and nowhere
 * else: every byte of input is generated by this same package and is
 * well-formed, so the cases a scanner gets wrong — implied end tags, unquoted
 * attributes, malformed nesting — cannot arise. If a fixture ever serves markup
 * it did not generate, this needs a parser instead.
 */

const VOID_ELEMENTS = new Set([
  'area',
  'base',
  'br',
  'col',
  'embed',
  'hr',
  'img',
  'input',
  'link',
  'meta',
  'source',
  'track',
  'wbr',
]);

/** Attributes a flow's targets can depend on. Everything else is presentation. */
const STRUCTURAL_ATTRIBUTES = new Set([
  'role',
  'type',
  'name',
  'for',
  'id',
  'action',
  'method',
  'aria-modal',
]);

/** Attributes that are structural only in whether they are present. */
const PRESENCE_ATTRIBUTES = new Set(['href', 'src', 'srcdoc']);

const TAG = /<(\/?)([a-zA-Z][a-zA-Z0-9-]*)((?:\s+[^>"']*(?:"[^"]*"|'[^']*')?)*)\s*(\/?)>/g;
const ATTRIBUTE = /([a-zA-Z-][a-zA-Z0-9-]*)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+)))?/g;

function attributesOf(raw: string): string[] {
  const kept: string[] = [];

  ATTRIBUTE.lastIndex = 0;
  let match: RegExpExecArray | null;
  while ((match = ATTRIBUTE.exec(raw)) !== null) {
    const name = match[1]?.toLowerCase() ?? '';
    const value = match[2] ?? match[3] ?? match[4] ?? '';

    if (STRUCTURAL_ATTRIBUTES.has(name)) {
      kept.push(`${name}=${value}`);
    } else if (PRESENCE_ATTRIBUTES.has(name)) {
      kept.push(`${name}:present`);
    }
  }

  return kept.sort();
}

/** Strip what carries no structure at all, so the scanner never sees it. */
function stripped(html: string): string {
  return html
    .replace(/<head\b[\s\S]*?<\/head>/gi, '')
    .replace(/<style\b[\s\S]*?<\/style>/gi, '')
    .replace(/<script\b[\s\S]*?<\/script>/gi, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<!doctype[^>]*>/gi, '');
}

/**
 * A page's structure as an indented outline, one element per line.
 *
 * Comparable with `toEqual`, and readable in a failure message — which matters,
 * because when this differs the useful question is *where*.
 */
export function structureOf(html: string): string {
  const lines: string[] = [];
  let depth = 0;

  TAG.lastIndex = 0;
  let match: RegExpExecArray | null;
  while ((match = TAG.exec(stripped(html))) !== null) {
    const closing = match[1] === '/';
    const tag = (match[2] ?? '').toLowerCase();
    const raw = match[3] ?? '';
    const selfClosing = match[4] === '/';

    if (closing) {
      depth = Math.max(0, depth - 1);
      continue;
    }

    const attributes = attributesOf(raw);
    lines.push(
      `${'  '.repeat(depth)}${tag}${attributes.length === 0 ? '' : `[${attributes.join(',')}]`}`,
    );

    if (!VOID_ELEMENTS.has(tag) && !selfClosing) {
      depth++;
    }
  }

  return lines.join('\n');
}
